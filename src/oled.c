// Each bit of a nibble doubled: 0b0101 -> 0b00110011. Scales a glyph column 2x vertically.
static const uint8_t spread4[16] = {
    0x00, 0x03, 0x0C, 0x0F, 0x30, 0x33, 0x3C, 0x3F,
    0xC0, 0xC3, 0xCC, 0xCF, 0xF0, 0xF3, 0xFC, 0xFF
};

// Full configuration, display still off. Every value is sent explicitly (the reset
// value unless noted, SSD1315 command tables) because oled_init() is also the recovery
// path after a bus error, when no hardware reset has put the registers back.
static const uint8_t init_cmds[] = {
    0xAE,               // display off
    0x2E,               // scrolling off
    0x20, 0x00,         // horizontal addressing mode (reset is page mode)
    0xA8, 0x3F,         // 64 MUX
    0xD3, 0x00,         // display offset 0
    0x40,               // display start line 0
    0xA1,               // column 127 -> SEG0 } together a 180 degree rotation: the WeAct
    0xC8,               // COM scan reversed  } orientation, pin header at the top
    0xDA, 0x12,         // alternative COM pins, no left/right remap
    0x81, 0x7F,         // contrast
    0xD5, 0x80,         // clock divide 1, oscillator setting 1000b
    0xD9, 0x22,         // pre-charge phase 1 and 2: 2 DCLK each
    0xDB, 0x20,         // VCOMH ~0.77 x VCC
    0xA4,               // output follows RAM
    0xA6,               // normal, not inverted
};

static const uint8_t on_cmds[] = {
    0x8D, 0x14,         // charge pump on, 7.5 V (must precede AFh)
    0xAF,               // display on; SEG/COM drive starts within 100 ms
};

static bool fail(void)
{
    i2c1_reset();
    return false;
}

// Start + address + control byte. On false the bus has already been reset.
static bool begin(uint8_t ctrl)
{
    if (!i2c1_start() || !i2c1_write(OLED_ADDR_W) || !i2c1_write(ctrl)) {
        return fail();
    }
    return true;
}

static bool end(void)
{
    return i2c1_stop() ? true : fail();
}

static bool send_cmds(const uint8_t *c, uint8_t n)
{
    if (!begin(OLED_CTRL_CMD)) {
        return false;
    }
    do {
        if (!i2c1_write(*c++)) {
            return fail();
        }
    } while (--n);
    return end();
}

// Limits the RAM write window: data then fills columns c0..c1 of page p0, wraps to c0
// of the next page, and so on up to p1 (horizontal addressing, SSD1315 21h/22h).
static bool set_window(uint8_t c0, uint8_t c1, uint8_t p0, uint8_t p1)
{
    uint8_t c[6];

    c[0] = 0x21; c[1] = c0; c[2] = c1;
    c[3] = 0x22; c[4] = p0; c[5] = p1;
    return send_cmds(c, sizeof c);
}

// Number of characters of s that fit between col and column 127, at width w per char.
static uint8_t fit(uint8_t col, const char *s, uint8_t w)
{
    uint8_t n = 0;
    uint8_t room = (uint8_t)(OLED_COLS - col);

    while (s[n] != '\0' && room >= w) {
        room -= w;
        n++;
    }
    return n;
}

static const uint8_t *glyph(char ch)
{
    uint8_t c = (uint8_t)ch;

    if (c < FONT_FIRST || c > FONT_LAST) {
        c = '?';
    }
    return font5x7[c - FONT_FIRST];
}

bool oled_init(void)
{
    if (!send_cmds(init_cmds, sizeof init_cmds) || !oled_clear()) {
        return false;
    }
    return send_cmds(on_cmds, sizeof on_cmds);
}

bool oled_clear(void)
{
    if (!set_window(0, OLED_COLS - 1, 0, OLED_PAGES - 1) || !begin(OLED_CTRL_DATA)) {
        return false;
    }
    for (uint8_t p = 0; p < OLED_PAGES; p++) {
        for (uint8_t c = 0; c < OLED_COLS; c++) {
            if (!i2c1_write(0x00)) {
                return fail();
            }
        }
    }
    return end();
}

bool oled_text(uint8_t col, uint8_t page, const char *s)
{
    uint8_t n;

    if (col >= OLED_COLS || page >= OLED_PAGES || (n = fit(col, s, 6)) == 0) {
        return true;
    }
    if (!set_window(col, (uint8_t)(col + n * 6 - 1), page, page) || !begin(OLED_CTRL_DATA)) {
        return false;
    }
    while (n--) {
        const uint8_t *g = glyph(*s++);

        for (uint8_t i = 0; i < 6; i++) {
            if (!i2c1_write(i < 5 ? g[i] : 0x00)) {
                return fail();
            }
        }
    }
    return end();
}

bool oled_text_2x(uint8_t col, uint8_t page, const char *s)
{
    uint8_t n;

    if (col >= OLED_COLS || page >= OLED_PAGES - 1 || (n = fit(col, s, 12)) == 0) {
        return true;
    }
    if (!set_window(col, (uint8_t)(col + n * 12 - 1), page, page + 1) ||
        !begin(OLED_CTRL_DATA)) {
        return false;
    }
    // The window wraps after the top page's last column, so send every character's top
    // half (glyph rows 0-3), then every bottom half (rows 4-7).
    for (uint8_t half = 0; half < 2; half++) {
        const char *p = s;

        for (uint8_t k = n; k; k--) {
            const uint8_t *g = glyph(*p++);

            for (uint8_t i = 0; i < 12; i++) {
                uint8_t b = 0x00;

                if (i < 10) {
                    b = g[i >> 1];
                    b = spread4[half ? b >> 4 : b & 0x0F];
                }
                if (!i2c1_write(b)) {
                    return fail();
                }
            }
        }
    }
    return end();
}
